"""Apple Background Assets (Apple-hosted asset pack) manifest draft.

STATUS: DRAFT, NOT VERIFIED ON macOS. The JSON layout follows the structure printed by
``xcrun ba-package template`` as documented for Xcode 26 (assetPackID, downloadPolicy,
fileSelectors, platforms). It was written without access to Xcode, so the macOS job of the
``readori-voice-packs.yml`` workflow in readori/test-env-setup dumps the real template and the
maintainer must compare the two before uploading anything to App Store Connect.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from .common import MANIFEST_NAME, VoicePackError, loads_strict, safe_relative_path
from .pack import apple_asset_pack_id

NOTES = """\
Apple Background Assets manifest - DRAFT, NOT VERIFIED

Generated by `python -m readori_voicepack ba-manifest`. The layout (assetPackID, downloadPolicy,
fileSelectors, platforms) was written from documentation, without running Xcode.

Before using it:
  1. On macOS with Xcode 26 run:  xcrun ba-package template > template.json
  2. Compare template.json with the generated manifest: key names, downloadPolicy shape,
     fileSelectors form (this draft lists every file explicitly) and the allowed characters of
     assetPackID.
  3. Build the archive:  xcrun ba-package <manifest.json> -o <pack>.aar   (flags unverified)
  4. Uploading the .aar to App Store Connect is a separate, manual maintainer step. No Apple
     credentials belong in this repository.

Download policy: onDemand. The user picks a voice pack in the app; nothing is installed
automatically with the app.
"""


def build_ba_manifest(pack_dir: Path) -> dict[str, Any]:
    manifest_path = pack_dir / MANIFEST_NAME
    if not manifest_path.is_file():
        raise VoicePackError(f"{MANIFEST_NAME} not found in {pack_dir}")
    manifest = loads_strict(manifest_path.read_text(encoding="utf-8"))
    pack_id = manifest.get("packId")
    if not isinstance(pack_id, str):
        raise VoicePackError("manifest has no packId")
    files = sorted(
        p.relative_to(pack_dir).as_posix() for p in pack_dir.rglob("*") if p.is_file()
    )
    for rel in files:
        if safe_relative_path(rel) != rel:
            raise VoicePackError(f"unsafe file name: {rel!r}")
    return {
        "assetPackID": apple_asset_pack_id(pack_id),
        "downloadPolicy": {"onDemand": {}},
        "fileSelectors": [{"file": rel} for rel in files],
        "platforms": ["iOS"],
    }
