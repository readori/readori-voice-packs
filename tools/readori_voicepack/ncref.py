"""Non-commercial reference list (``docs/NC_REFERENCE.md``), generated from the registry.

Models whose licence (or training data) forbids commercial use are excluded from every
pack, index, Apple asset pack and the community tier. This file only *lists* them with the
reason and the upstream page, so maintainers and users can see why they are missing.
Nothing here is built, hosted, downloaded or shown in Readori.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from .registry import load_registry

DEFAULT_NC_REFERENCE = Path("docs/NC_REFERENCE.md")

# Matches "CC-BY-NC-*", "Non-commercial", "non-commercial", "NC" as a word.
_NC = re.compile(r"\bNC\b|non-commercial|noncommercial", re.IGNORECASE)

HEADER = """# Non-commercial reference list / 非商用参考档

> Generated by `python -m readori_voicepack nc-reference` from `registry/models.yaml`. Do not edit by hand.
> 由 `python -m readori_voicepack nc-reference` 根据 `registry/models.yaml` 生成，请勿手改。

These models are **reference only**. Their licence or training data forbids commercial use,
and Readori is a paid app, so they are never built, hosted, put in `catalog/v1/index.json`,
packaged as Apple asset packs or offered in the community tier. The table only records what
was reviewed and why it was excluded; follow the upstream licence if you use a model yourself.

以下模型**只作参考**：许可证或训练数据禁止商用，而 Readori 是付费 App，因此不构建、不托管、
不进 `catalog/v1/index.json`、不做 Apple 资产包、也不进社区档。本表只记录审查过的模型及排除原因；
如自行使用，请遵守上游许可证。

| id | licence / 许可 | reason / 排除原因 | upstream / 上游 |
|---|---|---|---|
"""


def _cell(text: Any) -> str:
    value = " ".join(str(text or "").split())
    return value.replace("|", "\\|")


def is_non_commercial(entry: dict[str, Any]) -> bool:
    if entry.get("status") != "excluded":
        return False
    licence = entry.get("license") or {}
    haystack = " ".join(
        str(part or "")
        for part in (
            licence.get("spdx"),
            entry.get("excludedReason"),
            (licence.get("dataset") or {}).get("spdx"),
        )
    )
    return bool(_NC.search(haystack))


def _upstream_link(entry: dict[str, Any]) -> str:
    licence = entry.get("license") or {}
    for candidate in (licence.get("url"), (entry.get("upstream") or {}).get("url")):
        if isinstance(candidate, str) and candidate.startswith("https://"):
            return f"<{candidate}>"
    return ""


def render_nc_reference(models: list[dict[str, Any]]) -> str:
    rows = []
    for entry in sorted((m for m in models if is_non_commercial(m)), key=lambda m: m["id"]):
        licence = entry.get("license") or {}
        rows.append(
            "| {id} | {spdx} | {reason} | {link} |".format(
                id=_cell(entry["id"]),
                spdx=_cell(licence.get("spdx")),
                reason=_cell(entry.get("excludedReason")),
                link=_upstream_link(entry),
            )
        )
    return HEADER + "\n".join(rows) + "\n"


def write_nc_reference(registry_path: Path, out: Path) -> int:
    registry = load_registry(registry_path)
    text = render_nc_reference(registry.models)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    return text.count("\n| ") - 1


def check_nc_reference(registry_path: Path, out: Path) -> bool:
    registry = load_registry(registry_path)
    expected = render_nc_reference(registry.models)
    return out.is_file() and out.read_text(encoding="utf-8") == expected
